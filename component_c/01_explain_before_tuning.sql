-- ----------------------------------------------------------------------------
-- QUERY 1: Customer Order History with Status & Date Range Filtering
-- ----------------------------------------------------------------------------
-- Business Context:
--   Customer portal "My Orders" tab. Customer #4287 views their completed
--   or delivered orders placed within the last 180 days, ordered newest first.
--
-- Unindexed Baseline Expectation:
--   - No index on orders(customer_id) or orders(placed_at).
--   - Query planner is forced to execute a Parallel Sequential Scan across all
--     200,000 rows in the orders table.
--   - Reads thousands of shared buffer blocks from memory/disk.
--   - Filters 200,000 rows to extract ~10-25 matching rows, then Sorts.
-- ----------------------------------------------------------------------------

\echo '======================================================================'
\echo 'QUERY 1 (BEFORE TUNING): EXPLAIN (ANALYZE, BUFFERS)'
\echo '======================================================================'

EXPLAIN (ANALYZE, BUFFERS, VERBOSE, SETTINGS)
SELECT
    order_id,
    customer_id,
    status,
    placed_at,
    total_amount
FROM orders
WHERE customer_id = 4287
  AND status IN ('paid', 'shipped', 'delivered')
  AND placed_at >= NOW() - INTERVAL '180 days'
ORDER BY placed_at DESC;


-- ----------------------------------------------------------------------------
-- QUERY 2: Product Multi-Tag Discovery via Array Containment (GIN Candidate)
-- ----------------------------------------------------------------------------
-- Business Context:
--   Catalog search filter. A shopper searches for active products tagged with
--   both 'gaming' AND 'laptop' simultaneously (array containment operator @>).
--
-- Unindexed Baseline Expectation:
--   - No index on the array column products(tags).
--   - Postgres must perform a Sequential Scan over all 25,000 product rows.
--   - Evaluates the @> array containment predicate tuple by tuple.
--   - Significant CPU overhead and buffer reading.
-- ----------------------------------------------------------------------------

\echo '======================================================================'
\echo 'QUERY 2 (BEFORE TUNING): EXPLAIN (ANALYZE, BUFFERS)'
\echo '======================================================================'

EXPLAIN (ANALYZE, BUFFERS, VERBOSE, SETTINGS)
SELECT
    product_id,
    sku,
    title,
    unit_price,
    stock_qty,
    tags
FROM products
WHERE is_active = TRUE
  AND tags @> ARRAY['gaming', 'laptop']::TEXT[]
ORDER BY unit_price ASC;


-- ----------------------------------------------------------------------------
-- QUERY 3: Seller Quarterly Revenue & Product Performance Aggregation
-- ----------------------------------------------------------------------------
-- Business Context:
--   Merchant dashboard. Vendor #42 calculates total units sold and gross
--   revenue generated by each of their products over the past 120 days.
--
-- Unindexed Baseline Expectation:
--   - Missing foreign key indexes on order_items(product_id) and orders(placed_at).
--   - Planner performs massive Parallel Sequential Scans on order_items
--     (480,000 rows) and orders (200,000 rows).
--   - Expensive Hash Join / HashAggregate operations reading tens of thousands
--     of buffer blocks.
--   - High latency (hundreds of milliseconds).
-- ----------------------------------------------------------------------------

\echo '======================================================================'
\echo 'QUERY 3 (BEFORE TUNING): EXPLAIN (ANALYZE, BUFFERS)'
\echo '======================================================================'

EXPLAIN (ANALYZE, BUFFERS, VERBOSE, SETTINGS)
SELECT
    p.product_id,
    p.title,
    c.name AS category_name,
    COUNT(oi.order_item_id) AS total_order_items,
    SUM(oi.quantity) AS units_sold,
    SUM(oi.quantity * oi.unit_price_at_purchase) AS gross_revenue
FROM order_items oi
JOIN orders o ON o.order_id = oi.order_id
JOIN products p ON p.product_id = oi.product_id
JOIN categories c ON c.category_id = p.category_id
WHERE p.seller_id = 42
  AND o.status IN ('paid', 'shipped', 'delivered')
  AND o.placed_at >= NOW() - INTERVAL '120 days'
GROUP BY p.product_id, p.title, c.name
ORDER BY gross_revenue DESC;
